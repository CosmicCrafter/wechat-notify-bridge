"""Project the existing OpenAPI request contract into a checked Markdown reference."""

import argparse
import json
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = "docs/reference/HTTP-CONTRACT.md"


def cell(value):
    return (
        str(value).replace("|", "\\|").replace("\n", " ").replace("<", "&lt;").replace(">", "&gt;")
    )


def kind(schema):
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    for key in ("anyOf", "oneOf", "allOf"):
        if key in schema:
            return " / ".join(kind(s) for s in schema[key])
    if schema.get("type") == "array":
        return "array[" + kind(schema.get("items", {})) + "]"
    return schema.get("type", "未约束")


def constraints(schema):
    names = {
        "minLength": "最短",
        "maxLength": "最长",
        "minimum": "最小",
        "maximum": "最大",
        "exclusiveMinimum": "大于",
        "exclusiveMaximum": "小于",
        "minItems": "最少项",
        "maxItems": "最多项",
        "pattern": "模式",
        "enum": "枚举",
    }
    values = [
        label + " " + json.dumps(schema[key], ensure_ascii=False)
        for key, label in names.items()
        if key in schema
    ]
    if schema.get("additionalProperties") is False:
        values.append("拒绝未声明字段")
    return "；".join(values) or "—"


def render(schema):
    fingerprint = hashlib.sha256(
        json.dumps(schema, ensure_ascii=False, sort_keys=True).encode()
    ).hexdigest()
    lines = [
        "# HTTP 请求字段合同（自动生成）",
        "<!-- Generated by scripts/build_api_reference.py; do not edit. -->",
        "源规范（排序 JSON）SHA256：`" + fingerprint + "`。",
        f"适用服务 {schema['info']['version']}。来源是仓库 server/openapi.json；重建：`python scripts/build_api_reference.py`，检查加 `--check`。",
        "本页只陈述 OpenAPI 已声明的请求、参数和响应模型；不推断路由内部校验、动态授权、错误全集或平台送达。操作与运行错误见 [HTTP API 参考与错误处理](../server/API.md)。",
        "## 授权与阅读方式",
        "HTTPBearer 是应用 Key 或 OAuth 访问令牌，不是管理员密码。X-Notify-Receiver 在规范中是可选参数，但 protected 内容/操作按运行条件强制校验；legacy 兼容和配对例外见 [接收协议](../integration/RECEIVERS.md)。",
    ]
    operations = [
        (p, m, o)
        for p, item in schema["paths"].items()
        for m, o in item.items()
        if m in {"get", "post", "put", "patch", "delete"}
    ]
    lines += ["## 操作索引", "| 方法 | 路径 | 应用认证 | 请求体 |", "|---|---|---|---|"]
    for path, method, op in operations:
        body = (
            op.get("requestBody", {})
            .get("content", {})
            .get("application/json", {})
            .get("schema", {})
        )
        lines.append(
            f"| {method.upper()} | `{path}` | {'Bearer' if op.get('security') else '公开'} | {kind(body) if body else '无 JSON 请求体'} |"
        )
    lines.append("## 各操作的参数和声明响应")
    for path, method, op in operations:
        lines += [f"### {method.upper()} {path}", f"operationId：`{op['operationId']}`。"]
        if op.get("parameters"):
            lines += ["| 参数 | 位置 | 类型 | 必填 / 默认 | 约束 |", "|---|---|---|---|---|"]
            for parameter in op["parameters"]:
                spec = parameter.get("schema", {})
                default = "必填" if parameter.get("required") else "可选"
                if "default" in spec:
                    default += " / " + json.dumps(spec["default"], ensure_ascii=False)
                note = (
                    "条件授权，见页首"
                    if parameter["name"] == "X-Notify-Receiver"
                    else constraints(spec)
                )
                lines.append(
                    "| "
                    + " | ".join(
                        cell(v)
                        for v in [parameter["name"], parameter["in"], kind(spec), default, note]
                    )
                    + " |"
                )
        body = op.get("requestBody")
        if body:
            value = body.get("content", {}).get("application/json", {}).get("schema", {})
            lines.append(
                f"JSON 请求体：{kind(value)}，{'必需' if body.get('required') else '可选'}；字段见下方请求模型。"
            )
        responses = []
        for code, response in op.get("responses", {}).items():
            value = response.get("content", {}).get("application/json", {}).get("schema", {})
            responses.append(code + " → " + (kind(value) if value else "未声明完整 JSON 模型"))
        lines.append(
            "规范声明："
            + "；".join(responses)
            + "。未列 401/403/409 等不表示运行时不会出现；200 也不证明外发成功。"
        )
    lines.append("## 请求与校验模型")
    for name, model in schema.get("components", {}).get("schemas", {}).items():
        lines += [
            "### 模型 " + name,
            "额外字段："
            + ("拒绝" if model.get("additionalProperties") is False else "以规范为准")
            + "。",
            "| 字段 | 类型 | 必填 / 默认 | 约束 |",
            "|---|---|---|---|",
        ]
        required = model.get("required", [])
        for key, value in model.get("properties", {}).items():
            default = "必填" if key in required else "可选"
            if "default" in value:
                default += " / " + json.dumps(value["default"], ensure_ascii=False)
            lines.append(
                "| "
                + " | ".join(cell(v) for v in [key, kind(value), default, constraints(value)])
                + " |"
            )
    lines += [
        "## 规范之外仍需验证",
        "Pydantic 非空白、卡片模式组合、Bot/会话/接收能力、租约代际和平台状态等运行校验见 API.md 与对应操作指南。API 当前没有为所有成功响应提供精确 response_model，本页不把空 schema 填成想象的字段。示例和运行事实必须用测试或实际请求另证。",
    ]
    return ("\n\n".join(lines) + "\n").replace("|\n\n|", "|\n|")


def build(root=ROOT, *, check=False):
    target = root / OUTPUT
    text = render(json.loads((root / "server/openapi.json").read_text(encoding="utf-8")))
    if check:
        if not target.is_file() or target.read_text(encoding="utf-8") != text:
            raise ValueError(
                "Stale OpenAPI Markdown reference; run python scripts/build_api_reference.py"
            )
    else:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8")
    return target


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    print(build(check=parser.parse_args().check))
